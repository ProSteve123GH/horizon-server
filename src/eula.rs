//! Explicit EULA acceptance. Nothing here ever writes `eula=true` on the operator's behalf.

use std::fs;
use std::io::{self, Write};
use std::path::Path;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EulaState {
    AlreadyAccepted,
    AcceptedNow,
}

#[derive(Clone, Copy, Debug)]
pub struct EulaOptions<'a> {
    /// Explicit non-interactive acceptance (`--accept-eula` / `HORIZON_SERVER_ACCEPT_EULA=1`).
    pub explicit_accept: bool,
    /// Whether stdin is an interactive terminal. Tests inject this explicitly.
    pub interactive: bool,
    /// Optional injected answer for tests; production passes `None` and reads stdin.
    pub injected_answer: Option<&'a str>,
}

#[derive(Debug)]
pub enum EulaError {
    Io(io::Error),
    Declined,
    NeedsInteractiveAcceptance,
    Malformed(String),
}

impl std::fmt::Display for EulaError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Io(error) => write!(formatter, "I/O error reading/writing eula.txt: {error}"),
            Self::Declined => write!(formatter, "EULA was not accepted; the server will not start."),
            Self::NeedsInteractiveAcceptance => write!(
                formatter,
                "eula.txt is missing. In a terminal, answer the EULA prompt, or start \
                 non-interactively with --accept-eula after reading the EULA at \
                 https://aka.ms/MinecraftEULA"
            ),
            Self::Malformed(reason) => write!(formatter, "Invalid eula.txt: {reason}"),
        }
    }
}

impl std::error::Error for EulaError {}

impl From<io::Error> for EulaError {
    fn from(error: io::Error) -> Self {
        Self::Io(error)
    }
}

fn value_from_eula(text: &str) -> Option<bool> {
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') || trimmed.starts_with('!') {
            continue;
        }
        if let Some((key, value)) = trimmed.split_once('=') {
            if key.trim().eq_ignore_ascii_case("eula") {
                return match value.trim() {
                    "true" => Some(true),
                    "false" => Some(false),
                    other => Some(other.parse::<bool>().ok()?),
                };
            }
        }
    }
    None
}

fn write_eula(path: &Path) -> io::Result<()> {
    let contents = concat!(
        "# Generated by horizon-server. Read the Minecraft EULA before accepting:\n",
        "# https://aka.ms/MinecraftEULA\n",
        "# Acceptance must be given explicitly by the server operator.\n",
        "eula=true\n",
    );
    let temporary = path.with_extension("txt.tmp");
    fs::write(&temporary, contents)?;
    fs::rename(&temporary, path)
}

fn ask_on_terminal() -> io::Result<bool> {
    print!(
        "You must accept the Minecraft EULA to start this server.\n\
         Read it at https://aka.ms/MinecraftEULA\n\
         Type 'yes' to accept, or anything else to decline: "
    );
    io::stdout().flush()?;
    let mut answer = String::new();
    io::stdin().read_line(&mut answer)?;
    let answer = answer.trim();
    Ok(answer.eq_ignore_ascii_case("yes") || answer.eq_ignore_ascii_case("true"))
}

/// Ensure `eula.txt` records explicit acceptance. Returns how acceptance was obtained.
pub fn ensure_eula(dir: &Path, options: EulaOptions<'_>) -> Result<EulaState, EulaError> {
    let path = dir.join("eula.txt");
    match fs::read_to_string(&path) {
        Ok(text) => match value_from_eula(&text) {
            Some(true) => Ok(EulaState::AlreadyAccepted),
            Some(false) => Err(EulaError::Declined),
            None => Err(EulaError::Malformed(
                "no eula=true or eula=false entry was found".to_owned(),
            )),
        },
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            let accepted = if options.explicit_accept {
                true
            } else if options.interactive {
                match options.injected_answer {
                    Some(answer) => {
                        answer.trim().eq_ignore_ascii_case("yes")
                            || answer.trim().eq_ignore_ascii_case("true")
                    }
                    None => ask_on_terminal()?,
                }
            } else {
                return Err(EulaError::NeedsInteractiveAcceptance);
            };
            if !accepted {
                return Err(EulaError::Declined);
            }
            write_eula(&path)?;
            Ok(EulaState::AcceptedNow)
        }
        Err(error) => Err(EulaError::Io(error)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(name: &str) -> std::path::PathBuf {
        let dir = std::env::temp_dir().join(format!("horizon-eula-test-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn missing_eula_in_non_interactive_mode_never_writes() {
        let dir = scratch("noninteractive");
        let result = ensure_eula(
            &dir,
            EulaOptions {
                explicit_accept: false,
                interactive: false,
                injected_answer: None,
            },
        );
        assert!(matches!(result, Err(EulaError::NeedsInteractiveAcceptance)));
        assert!(!dir.join("eula.txt").exists());
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn explicit_acceptance_writes_true() {
        let dir = scratch("explicit");
        let state = ensure_eula(
            &dir,
            EulaOptions {
                explicit_accept: true,
                interactive: false,
                injected_answer: None,
            },
        )
        .unwrap();
        assert_eq!(state, EulaState::AcceptedNow);
        let text = fs::read_to_string(dir.join("eula.txt")).unwrap();
        assert!(text.contains("eula=true"));
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn decline_never_writes_and_existing_false_blocks() {
        let dir = scratch("decline");
        let result = ensure_eula(
            &dir,
            EulaOptions {
                explicit_accept: false,
                interactive: true,
                injected_answer: Some("no"),
            },
        );
        assert!(matches!(result, Err(EulaError::Declined)));
        assert!(!dir.join("eula.txt").exists());

        fs::write(dir.join("eula.txt"), "# note\neula=false\n").unwrap();
        let result = ensure_eula(
            &dir,
            EulaOptions {
                explicit_accept: true,
                interactive: false,
                injected_answer: None,
            },
        );
        assert!(matches!(result, Err(EulaError::Declined)));
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn existing_true_is_accepted_without_rewriting() {
        let dir = scratch("existing");
        fs::write(dir.join("eula.txt"), "# operator note\neula=true\n").unwrap();
        let state = ensure_eula(
            &dir,
            EulaOptions {
                explicit_accept: false,
                interactive: false,
                injected_answer: None,
            },
        )
        .unwrap();
        assert_eq!(state, EulaState::AlreadyAccepted);
        assert_eq!(
            fs::read_to_string(dir.join("eula.txt")).unwrap(),
            "# operator note\neula=true\n"
        );
        fs::remove_dir_all(&dir).unwrap();
    }
}
